import {DatabaseSync} from 'node:sqlite';
import {mkdirSync,writeFileSync,chmodSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
const dir=resolve(process.env.DATA_DIR||'data');
const db=new DatabaseSync(join(dir,'hub.sqlite'));
db.exec('PRAGMA busy_timeout=10000');
const kinds=['customers','conversations','messages','crm_profiles'];
const stamp=new Date().toISOString().replace(/[:.]/g,'-');
const folder=join(dir,'backups','chat-supabase-'+stamp);
mkdirSync(folder,{recursive:true,mode:0o700});
db.exec(`VACUUM INTO '${join(folder,'hub.sqlite').replaceAll("'","''")}'`);
chmodSync(join(folder,'hub.sqlite'),0o600);
const snapshot=new DatabaseSync(join(folder,'hub.sqlite'),{readOnly:true});
const rows=snapshot.prepare(`SELECT kind,id,data,version,updated_at FROM records WHERE kind IN (${kinds.map(()=>'?').join(',')}) ORDER BY kind,id`).all(...kinds);
const escape=v=>'"'+String(v).replaceAll('"','""')+'"';
const csv=['kind,id,data,version,updated_at',...rows.map(r=>[r.kind,r.id,r.data,r.version,r.updated_at].map(escape).join(','))].join('\r\n');
writeFileSync(join(folder,'chat-crm.csv'),csv,{mode:0o600});
const counts=Object.fromEntries(kinds.map(k=>[k,rows.filter(r=>r.kind===k).length]));
const manifest={at:stamp,counts,total:rows.length,csvSha256:createHash('sha256').update(csv).digest('hex'),orphans:snapshot.prepare("SELECT COUNT(*) AS n FROM records m LEFT JOIN records c ON c.kind='conversations' AND c.id=json_extract(m.data,'$.conversationId') WHERE m.kind='messages' AND c.id IS NULL").get().n};
writeFileSync(join(folder,'manifest.json'),JSON.stringify(manifest,null,2),{mode:0o600});
snapshot.close();db.close();
console.log(JSON.stringify({folder,...manifest}));
